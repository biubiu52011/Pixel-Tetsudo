
create table if not exists public.train_timetables (
  id bigint generated by default as identity primary key,
  canonical_key text not null unique,
  calendar_urn text not null,
  primary_train_number text,
  lead_source_template_id bigint not null references public.manual_timetable_templates(id),
  group_evidence text not null check (group_evidence in ('source_only','verified_shared_itinerary','verified_continuation')),
  timetable_validity text not null default 'undated_not_current_verified' check (timetable_validity in ('undated_not_current_verified','date_verified')),
  source_revision_date date,
  created_at timestamptz not null default now()
);
comment on table public.train_timetables is 'Canonical train-first timetable identities; line timetables are projections. Historical/undated templates are never asserted live.';
create index if not exists train_timetables_calendar_idx on public.train_timetables(calendar_urn,primary_train_number);
create index if not exists train_timetables_lead_idx on public.train_timetables(lead_source_template_id);

create table if not exists public.train_timetable_continuity (
  from_template_id bigint primary key references public.manual_timetable_templates(id),
  to_template_id bigint not null unique references public.manual_timetable_templates(id),
  junction_station_urn text not null,
  arrival_clock text not null,
  departure_clock text not null,
  connection_minutes integer not null check (connection_minutes between 0 and 30),
  evidence text not null check(evidence in ('reciprocal_source_ids_station_time_revision')),
  created_at timestamptz not null default now(),
  constraint continuity_not_self check(from_template_id <> to_template_id)
);
comment on table public.train_timetable_continuity is 'Only verified same-train adjoining source timetable portions; no heuristic or station-only merges.';

create table if not exists public.train_timetable_members (
  source_template_id bigint primary key references public.manual_timetable_templates(id),
  timetable_id bigint not null references public.train_timetables(id) on delete cascade,
  segment_order integer not null default 0 check(segment_order >= 0),
  member_role text not null check(member_role in ('primary','duplicate_itinerary','verified_continuation')),
  first_stop_sequence integer not null,
  last_stop_sequence integer not null,
  stop_offset integer not null default 0 check(stop_offset >= 0),
  merge_first_stop boolean not null default false,
  constraint valid_stop_range check(first_stop_sequence <= last_stop_sequence),
  constraint no_merged_first_for_alias check(not (member_role='duplicate_itinerary' and merge_first_stop))
);
comment on table public.train_timetable_members is 'Persisted order and offsets of source timetable portions. No runtime inference of through service.';
create index if not exists train_timetable_members_run_idx on public.train_timetable_members(timetable_id,segment_order,source_template_id);
create index if not exists train_timetable_members_role_idx on public.train_timetable_members(member_role,timetable_id);

alter table public.train_timetables enable row level security;
alter table public.train_timetable_continuity enable row level security;
alter table public.train_timetable_members enable row level security;
revoke all on public.train_timetables, public.train_timetable_continuity, public.train_timetable_members from anon,authenticated;
grant select,insert,update,delete on public.train_timetables,public.train_timetable_continuity,public.train_timetable_members to service_role;

