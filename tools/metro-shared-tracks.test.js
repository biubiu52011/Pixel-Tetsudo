const fs=require('fs'),vm=require('vm'),assert=require('assert');
const db=JSON.parse(fs.readFileSync('data/core/railway_data.json')).lines;
const raw={Yurakucho:[],Fukutoshin:[],Namboku:[],Mita:[]};
const w={RailwayDB:{getAllLines:()=>db},DataLayer:{getAllLines:()=>db},DataFusion:{getRealtimePositions:id=>raw[id]||[]}};
const c={window:w,console,getLinesData:()=>db};vm.createContext(c);
for(const f of ['js/trains-data.js','js/trains-geometry.js'])vm.runInContext(fs.readFileSync(f,'utf8'),c);
const api=w.SharedTrackPairs;
assert(api.isSharedStation('Yurakucho','Wakoshi','Fukutoshin'));
assert(api.isSharedStation('Yurakucho','Kotake-Mukaihara','Fukutoshin'));
for(const station of ['Senkawa','Kanamecho','Ikebukuro'])assert(!api.isSharedStation('Yurakucho',station));
assert(!api.isSharedStation('Yurakucho','Wakoshi','Tojo'),'shared station must not hide unrelated transfers');
const p={trainId:'F01',stationIndex:2,segmentToIndex:3,segmentProgress:.4,destinationStation:'Shonandai',vehiclePlan:{models:['東急5050系']}};
const projected=api.projectPosition('Yurakucho','Fukutoshin',p);
assert.equal(projected.stationIndex,2);assert(Math.abs(projected.segmentProgress-.4)<1e-8);
assert.equal(projected.destinationStation,'Shonandai');assert.equal(projected.vehiclePlan,p.vehiclePlan);
assert(!projected.fusionLineId,'shared train stays on the current map geometry');
assert(!api.projectPosition('Yurakucho','Fukutoshin',{...p,stationIndex:5,segmentToIndex:6,segmentProgress:.01}),'after Kotake must leave peer map');
assert(api.projectPosition('Yurakucho','Fukutoshin',{...p,stationIndex:6,segmentToIndex:5,segmentProgress:1}),'arriving at Kotake enters shared map');
assert(!api.projectPosition('Yurakucho','Fukutoshin',{...p,stationIndex:8,segmentToIndex:null}));
assert(api.isSharedStation('Namboku','Shirokanedai','Mita'));
raw.Yurakucho=[{...p,trainId:'Y01',destinationStation:'ShinKiba'}];
raw.Fukutoshin=[p,p,{...p,trainId:'outside',stationIndex:6,segmentToIndex:null}];
let list=c.getRealtimePositions('Yurakucho');
assert.equal(list.length,2);assert.equal(list.find(x=>x.trainId==='F01').destinationStation,'Shonandai');
raw.Yurakucho.push(p);assert.equal(c.getRealtimePositions('Yurakucho').length,2,'same source train appears once');
raw.Fukutoshin=[];raw.Yurakucho=[{...p,trainId:'Y01',destinationStation:'ShinKiba'}];
assert.equal(c.getRealtimePositions('Fukutoshin')[0].destinationStation,'ShinKiba','reverse view shares Y services');
const page=fs.readFileSync('js/trains-page.js','utf8');
assert(page.includes('_dependencies.concat(window.SharedTrackPairs.getSharedLines(lineId))'));
console.log('Shared physical section, split boundary, fractional projection, retained service/model, symmetric map merge, dedupe and active peer loading PASS');
